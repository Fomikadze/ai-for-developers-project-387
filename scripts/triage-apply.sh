#!/usr/bin/env bash
# Применяет результат автотриажа (issue-triage.yml): проверяет ответ агента,
# ставит метки из белого списка и пишет один комментарий.
# Переменные: GH_TOKEN, GITHUB_REPOSITORY, ISSUE_NUMBER, TRIAGE_RESULT.
set -euo pipefail

# Ответ агента недоверенный: принимаем только известные значения.
if ! jq -e '
  (.category | IN("bug", "enhancement")) and
  (.state | IN("needs-triage", "needs-info")) and
  ([.summary, .recommendation] | all(type == "string" and length > 0)) and
  (.questions | type == "array" and all(type == "string")) and
  (.related | type == "array" and all(type == "number" and . == floor and . > 0)) and
  (.state != "needs-info" or (.questions | length > 0))
' <<<"$TRIAGE_RESULT" >/dev/null; then
  echo "::error::Ответ агента не прошёл проверку"
  exit 1
fi

# Пока агент работал, человек мог принять решение или закрыть обращение.
issue="$(gh issue view "$ISSUE_NUMBER" --repo "$GITHUB_REPOSITORY" --json state,labels)"
if ! jq -e '
  .state == "OPEN" and
  ([.labels[].name] | all(
    (IN("ready-for-agent", "ready-for-human", "needs-info", "wontfix") | not) and
    (startswith("wayfinder:") | not)))
' <<<"$issue" >/dev/null; then
  echo "Обращение закрыто или уже разобрано, изменений нет"
  exit 0
fi

# Категорию, выбранную автором, не меняем. needs-info заменяет needs-triage.
labels="$(jq -r --argjson issue "$issue" '
  [.state] + (if [$issue.labels[].name] | any(IN("bug", "enhancement")) then [] else [.category] end)
  | join(",")' <<<"$TRIAGE_RESULT")"
args=(--add-label "$labels")
if jq -e --argjson issue "$issue" \
  '.state == "needs-info" and ([$issue.labels[].name] | any(. == "needs-triage"))' \
  <<<"$TRIAGE_RESULT" >/dev/null; then
  args+=(--remove-label needs-triage)
fi

# Дисклеймер обязателен по скиллу triage. Упоминания обезврежены, длина ограничена.
body="$(jq -r --argjson self "$ISSUE_NUMBER" '
  def clean: gsub("\\s+"; " ") | gsub("@"; "@​") | gsub("<"; "&lt;") | .[0:600];
  def section($title; $items): if $items == [] then [] else ["", "**\($title)**", ""] + ($items | map("- " + .)) end;
  ["> *This was generated by AI during triage.*", "", "## Triage Notes", "",
   "**Категория:** `\(.category)`, **состояние:** `\(.state)`", "", (.summary | clean)]
  + section("Что нужно уточнить:"; if .state == "needs-info" then (.questions[0:5] | map(clean)) else [] end)
  + section("Похожие обращения:"; (.related - [$self])[0:5] | map("#\(.)"))
  + ["", "**Предлагаемый следующий шаг:** \(.recommendation | clean)"]
  | join("\n")' <<<"$TRIAGE_RESULT")"

gh issue comment "$ISSUE_NUMBER" --repo "$GITHUB_REPOSITORY" --body "$body"
gh issue edit "$ISSUE_NUMBER" --repo "$GITHUB_REPOSITORY" "${args[@]}"
